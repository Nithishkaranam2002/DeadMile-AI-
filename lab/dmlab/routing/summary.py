"""Summary table per solver and slice, read back from MLflow.

Nothing here is typed by hand: every number is read from the child runs of a
campaign in the routing-baselines experiment. Medians of distance, gap and
vehicles are over feasible runs only (said in the table header).

Sanity checks (bug detectors, never something to tune):
* any negative gap to the best known solution, which almost certainly means a
  units or rounding bug;
* a PyVRP median gap on Solomon above 2%.
"""

import statistics
from collections import defaultdict
from typing import Any

from mlflow import MlflowClient

from dmlab.routing.runner import EXPERIMENT
from dmlab.tracking import configure_mlflow

SLICE_ORDER = ["C1", "C2", "R1", "R2", "RC1", "RC2", "Boston", "Chicago"]
SOLVER_ORDER = ["pyvrp", "ortools", "nn"]
PYVRP_GAP_ALARM_PCT = 2.0


def fetch_runs(campaign: str) -> list[dict[str, Any]]:
    configure_mlflow()
    client = MlflowClient()
    exp = client.get_experiment_by_name(EXPERIMENT)
    if exp is None:
        return []
    runs = client.search_runs(
        [exp.experiment_id],
        filter_string=f"tags.campaign = '{campaign}' and tags.run_kind = 'solve'",
        max_results=50_000,
        order_by=["attributes.start_time DESC"],
    )
    latest: dict[tuple[str, str], dict[str, Any]] = {}
    for r in runs:  # newest first: keep the latest run per (solver, instance)
        key = (r.data.tags["solver"], r.data.tags["instance"])
        if key not in latest:
            latest[key] = {
                "run_id": r.info.run_id,
                "tags": r.data.tags,
                "metrics": r.data.metrics,
            }
    return list(latest.values())


def _med(values: list[float]) -> float | None:
    return statistics.median(values) if values else None


def build_rows(runs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    groups: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for r in runs:
        groups[(r["tags"]["solver"], r["tags"]["slice"])].append(r)

    def order(key: tuple[str, str]) -> tuple[int, int]:
        s, sl = key
        return (
            SOLVER_ORDER.index(s) if s in SOLVER_ORDER else 99,
            SLICE_ORDER.index(sl) if sl in SLICE_ORDER else 99,
        )

    rows = []
    for key in sorted(groups, key=order):
        solver, slc = key
        rs = groups[key]
        feas = [r for r in rs if r["metrics"].get("feasible") == 1.0]
        gaps = [r["metrics"]["gap_to_bks_pct"] for r in feas if "gap_to_bks_pct" in r["metrics"]]
        rows.append(
            {
                "solver": solver,
                "slice": slc,
                "runs": len(rs),
                "feasible": len(feas),
                "median_distance": _med([r["metrics"]["total_distance"] for r in feas]),
                "distance_unit": rs[0]["tags"].get("distance_unit", ""),
                "median_gap_pct": _med(gaps),
                "min_gap_pct": min(gaps) if gaps else None,
                "median_runtime_s": _med([r["metrics"]["runtime_s"] for r in rs]),
                "median_vehicles": _med([r["metrics"]["vehicles_used"] for r in feas]),
                "two_van_routes": (
                    sum(1 for r in feas if r["metrics"]["vehicles_used"] >= 2)
                    if rs[0]["tags"].get("source") == "amazon"
                    else None
                ),
            }
        )
    return rows


def sanity_problems(runs: list[dict[str, Any]], rows: list[dict[str, Any]]) -> list[str]:
    problems = []
    for r in runs:
        gap = r["metrics"].get("gap_to_bks_pct")
        if gap is not None and gap < 0:
            problems.append(
                f"negative gap {gap:.3f}% for {r['tags']['solver']} on {r['tags']['instance']} "
                f"(run {r['run_id']}): likely a units or rounding bug"
            )
    pyvrp_gaps = [
        r["metrics"]["gap_to_bks_pct"]
        for r in runs
        if r["tags"]["solver"] == "pyvrp"
        and r["tags"]["source"] == "solomon"
        and r["metrics"].get("feasible") == 1.0
        and "gap_to_bks_pct" in r["metrics"]
    ]
    if pyvrp_gaps and statistics.median(pyvrp_gaps) > PYVRP_GAP_ALARM_PCT:
        problems.append(
            f"PyVRP median Solomon gap {statistics.median(pyvrp_gaps):.2f}% is above "
            f"{PYVRP_GAP_ALARM_PCT}%"
        )
    return problems


def _fmt(v: float | None, digits: int = 1) -> str:
    return "n/a" if v is None else f"{v:,.{digits}f}"


def to_markdown(campaign: str, rows: list[dict[str, Any]], problems: list[str]) -> str:
    lines = [
        f"# Routing baselines, campaign `{campaign}`",
        "",
        "Generated by `dmlab-route summary` from MLflow runs (experiment "
        f"`{EXPERIMENT}`). Medians of distance, gap and vehicles are over feasible runs only.",
        "",
        "* Solomon distances are abstract benchmark units (not miles). Gap is against the "
        "distance only best known solution under the DIMACS convention floor(10 x d), "
        "verified by our checker (data/bks.csv).",
        "* Amazon distances are haversine straight-line km on stop coordinates (not road "
        "distance). 2 vans per route and a 10 h shift are assumptions. No best known "
        "solution exists, so no gap.",
        "",
        "| Solver | Slice | Feasible | Median distance | Unit | Median gap % | "
        "Median runtime s | Median vehicles | Routes using 2 vans |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['solver']} | {r['slice']} | {r['feasible']}/{r['runs']} | "
            f"{_fmt(r['median_distance'])} | {r['distance_unit']} | "
            f"{_fmt(r['median_gap_pct'], 2)} | {_fmt(r['median_runtime_s'])} | "
            f"{_fmt(r['median_vehicles'], 1)} | "
            f"{'n/a' if r['two_van_routes'] is None else r['two_van_routes']} |"
        )
    lines += ["", "## Sanity checks", ""]
    lines += [f"* FAILED: {p}" for p in problems] or [
        f"* No negative gaps; PyVRP Solomon median gap within {PYVRP_GAP_ALARM_PCT}%."
    ]
    return "\n".join(lines) + "\n"
