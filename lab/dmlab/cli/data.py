"""dmlab-data: fetch datasets and build data/bks.csv.

uv run dmlab-data fetch-solomon
uv run dmlab-data build-bks
uv run dmlab-data fetch-amazon
"""

import argparse
import hashlib
import json
import zipfile
from datetime import date
from pathlib import PurePosixPath

import yaml

from dmlab.data.amazon import build_instance, candidate_order, stream_select, write_processed
from dmlab.data.bks import build as build_bks
from dmlab.data.download import download_file, stream_chunks
from dmlab.paths import CONFIG_DIR, LAB_DIR, datasets_config


def fetch_solomon() -> None:
    cfg = datasets_config()["solomon"]
    zip_path = LAB_DIR / "data/raw/solomon_zip/solomon-100.zip"
    download_file(cfg["source_url"], zip_path, max_bytes=5_000_000)
    digest = hashlib.sha256(zip_path.read_bytes()).hexdigest()
    if digest != cfg["archive_sha256"]:
        raise SystemExit(f"Solomon archive sha256 {digest} does not match configs/datasets.yaml")
    out = LAB_DIR / cfg["raw_dir"]
    out.mkdir(parents=True, exist_ok=True)
    count = 0
    with zipfile.ZipFile(zip_path) as z:
        for info in z.infolist():
            p = PurePosixPath(info.filename)
            # Only the 56 instance files under In/, written by base name only.
            if len(p.parts) == 2 and p.parts[0] == "In" and p.suffix == ".txt":
                (out / p.name).write_bytes(z.read(info))
                count += 1
    print(f"Solomon: {count} instance files in {out}")


def build_bks_cmd() -> None:
    cfg = datasets_config()
    rows = build_bks(
        LAB_DIR / cfg["solomon"]["raw_dir"],
        LAB_DIR / "data/raw/bks_sources",
        cfg["bks"],
        LAB_DIR / "data/bks.csv",
    )
    dimacs = [r for r in rows if r["objective"] == "distance_only"]
    ok = sum(1 for r in dimacs if r["distance"])
    print(f"bks.csv: {ok}/{len(dimacs)} distance only values verified, {len(rows)} rows")


def fetch_amazon() -> None:
    cfg = datasets_config()["amazon"]
    files = cfg["files"]
    raw_dir = LAB_DIR / cfg["raw_dir"]
    base = cfg["base_url"]
    total = sum(f["size_bytes"] for f in files.values())
    print(f"Amazon eval set: {total / 1e6:,.1f} MB transfer in total; only route data is stored.")

    route_path = download_file(
        f"{base}/{files['route_data']['name']}",
        raw_dir / files["route_data"]["name"],
        max_bytes=files["route_data"]["size_bytes"],
    )
    route_raw = route_path.read_bytes()
    route_data = json.loads(route_raw)
    order = candidate_order(route_data, cfg["cities"], cfg["subset_seed"])
    n = cfg["routes_per_city"]
    # Check a pool of 3 x N candidates per city, in seeded order.
    pool = {city: rids[: 3 * n] for city, rids in order.items()}
    keep = {rid for rids in pool.values() for rid in rids}
    print(f"Candidates: {', '.join(f'{c} {len(r)}' for c, r in order.items())}; pool {len(keep)}")

    print(f"Streaming {files['package_data']['name']} ...")
    packages = stream_select(stream_chunks(f"{base}/{files['package_data']['name']}"), keep)
    print(f"Streaming {files['travel_times']['name']} ...")
    travel = stream_select(stream_chunks(f"{base}/{files['travel_times']['name']}"), keep)

    a = cfg["assumptions"]
    processed = LAB_DIR / cfg["processed_dir"]
    selected: dict[str, list[str]] = {}
    excluded: list[dict[str, str]] = []
    for city, rids in pool.items():
        selected[city] = []
        for rid in rids:
            if len(selected[city]) == n:
                break
            route = route_data[rid]
            if rid not in packages or rid not in travel:
                excluded.append({"route_id": rid, "city": city, "reason": "missing in a file"})
                continue
            inst, problems = build_instance(
                rid,
                route,
                packages[rid],
                travel[rid],
                city,
                a["vans_per_route"],
                a["shift_hours"],
                "check",
            )
            if inst is None:
                excluded.append({"route_id": rid, "city": city, "reason": "; ".join(problems)})
                continue
            write_processed(processed / f"{rid}.json", rid, city, route, packages[rid], travel[rid])
            selected[city].append(rid)
        print(f"{city}: selected {len(selected[city])}")

    subset = {
        "generated_by": "uv run dmlab-data fetch-amazon",
        "generated_on": date.today().isoformat(),
        "route_data_sha256": hashlib.sha256(route_raw).hexdigest(),
        "subset_seed": cfg["subset_seed"],
        "routes_per_city": n,
        "selected": selected,
        "excluded": excluded,
    }
    header = (
        "# Amazon Last Mile subset, generated by dmlab-data fetch-amazon. Do not edit.\n"
        "# Routes are taken in seeded order; a route is excluded only by data checks\n"
        "# done before any solver runs (reason recorded below).\n"
    )
    path = CONFIG_DIR / "amazon_subset.yaml"
    path.write_text(header + yaml.safe_dump(subset, sort_keys=False, width=100))
    print(f"Wrote {path.relative_to(LAB_DIR)}; excluded {len(excluded)} routes")


def main() -> None:
    parser = argparse.ArgumentParser(prog="dmlab-data")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("fetch-solomon", help="download and unpack the 56 Solomon instances")
    sub.add_parser("build-bks", help="build and verify data/bks.csv")
    sub.add_parser("fetch-amazon", help="stream the Amazon eval set and keep the subset")
    args = parser.parse_args()
    {"fetch-solomon": fetch_solomon, "build-bks": build_bks_cmd, "fetch-amazon": fetch_amazon}[
        args.cmd
    ]()


if __name__ == "__main__":
    main()
